constexpr unsigned kMinMs = 1500;    // shown at least this long before a button counts
constexpr unsigned kPulseMs = 1200;  // the prompt's pulse period once a button counts
constexpr uint32_t kVramOff = 0x88000u;
constexpr int kStride = 512;
constexpr uint32_t kKeys = PSP_CTRL_SELECT | PSP_CTRL_START | PSP_CTRL_UP | PSP_CTRL_RIGHT | PSP_CTRL_DOWN |
                           PSP_CTRL_LEFT | PSP_CTRL_LTRIGGER | PSP_CTRL_RTRIGGER | PSP_CTRL_TRIANGLE |
                           PSP_CTRL_CIRCLE | PSP_CTRL_CROSS | PSP_CTRL_SQUARE;

inline uint32_t pix(unsigned r, unsigned g, unsigned b) { return 0xFF000000u | b << 16 | g << 8 | r; }  // ABGR

int qrDark(int mx, int my) {
    const int n = spl_qr[0], stride = (n + 7) / 8;
    if (mx < 0 || my < 0 || mx >= n || my >= n) return 0;
    return (spl_qr[1 + my * stride + (mx >> 3)] >> (7 - (mx & 7))) & 1;
}

// One scanline (the arithmetic of splash_gen.py render(): the previews equal what this draws).
void drawRow(volatile uint32_t* dst, int y, int lvl) {
    uint32_t line[SPL_W];  // 1.9 KB of the main thread's stack while the splash is up (no .bss)
    const uint32_t t = SPL_BG_TOP, b = SPL_BG_BOT;
    const unsigned k = SPL_H - 1, uy = static_cast<unsigned>(y);
    const unsigned r = ((t >> 16 & 255) * (k - uy) + (b >> 16 & 255) * uy) / k;
    const unsigned g = ((t >> 8 & 255) * (k - uy) + (b >> 8 & 255) * uy) / k;
    const unsigned bl = ((t & 255) * (k - uy) + (b & 255) * uy) / k;
    const uint32_t bg = pix(r, g, bl);
    for (int x = 0; x < SPL_W; x++) line[x] = bg;
    const int n = spl_qr[0], panel = (n + 2 * SPL_QUIET) * SPL_MOD;
    if (y >= SPL_PY && y < SPL_PY + panel) {
        const int my = (y - SPL_PY) / SPL_MOD - SPL_QUIET;
        for (int x = SPL_PX; x < SPL_PX + panel; x++)
            line[x] = qrDark((x - SPL_PX) / SPL_MOD - SPL_QUIET, my) ? 0xFF000000u : 0xFFFFFFFFu;
    }
    if (y >= SPL_DIV_Y && y < SPL_DIV_Y + SPL_DIV_H) {
        const uint32_t d = pix(SPL_DIV_RGB >> 16 & 255, SPL_DIV_RGB >> 8 & 255, SPL_DIV_RGB & 255);
        for (int x = SPL_DIV_X; x < SPL_DIV_X + SPL_DIV_W; x++) line[x] = d;
    }
    for (int i = 0; i < SPL_NITEMS; i++) {
        const SplItem& it = spl_items[i];
        if (y < it.y || y >= it.y + it.h) continue;
        const unsigned level = i == SPL_PROMPT ? static_cast<unsigned>(lvl) : 256u;
        const unsigned char* row = spl_alpha + it.off + static_cast<unsigned>(y - it.y) * static_cast<unsigned>((it.w + 1) / 2);
        for (int c = 0; c < it.w; c++) {
            unsigned a = static_cast<unsigned>(c & 1 ? row[c >> 1] & 15 : row[c >> 1] >> 4) * 17u;
            if (!a) continue;
            a = (a * level + 128u) >> 8;
            const uint32_t p = line[it.x + c];
            const unsigned pr = p & 255, pg = p >> 8 & 255, pb = p >> 16 & 255;
            line[it.x + c] = pix((pr * (255u - a) + it.r * a + 127u) / 255u, (pg * (255u - a) + it.g * a + 127u) / 255u,
                                 (pb * (255u - a) + it.b * a + 127u) / 255u);
        }
    }
    for (int x = 0; x < SPL_W; x++) dst[x] = line[x];
}

// The prompt's level (0..256): dim until a button counts, then a triangle pulse between 110 and full.
int promptLevel(unsigned ms) {
    if (ms < kMinMs) return SPL_LVL_DIM;
    const unsigned ph = (ms - kMinMs) % kPulseMs, half = kPulseMs / 2;
    const unsigned tri = ph < half ? half - ph : ph - half;  // starts at full brightness
    return 110 + static_cast<int>(tri * 146u / half);
}

