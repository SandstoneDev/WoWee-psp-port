// The community QR splash (psp_splash.hpp).
//
// Shown once per start from main(), after displayInit() and the configuration (wowee.cfg, autotest.txt) and before
// anything loads: the login screen, the intro movie, the audio and the network all come after it. The only switch is
// the build: the CMake option WOWEE_PSP_SPLASH (default ON) compiles this file in and defines WOWEE_PSP_SPLASH for
// main_psp.cpp. There is no wowee.cfg key for it.
//
// Picture: 480x272, 8888, drawn by the CPU one scanline at a time into VRAM offset 0x88000 (stride 512, 544 KB in
// all). That range is the depth buffer and the start of the VRAM store, both still unused at this point (the
// first frame clears the depth, the models fill the store later); the two 5551 colour buffers at VRAM 0 are not
// touched. sceDisplaySetFrameBuf shows it; afterwards the display gets back exactly the frame buffer, width and
// format it had before (sceDisplayGetFrameBuf), so the GE and the display are as displayInit() left them.
// Layout: a vertical background gradient, the white QR panel on the left (29x29 modules of 6 px plus the 4-module
// quiet zone), anti-aliased English text on the right; "Press any button to continue" is dim for the first
// kMinMs, then pulses.
// The text is not drawn from a font at run time: tools/psp/splash/splash_gen.py renders each line once with
// DejaVu Sans into a 4-bit alpha bitmap and writes the bitmaps, the QR matrix and the layout into the GENERATED
// block below (its previews use this file's integer arithmetic, so they show exactly what the PSP draws).
//
// Input: any of the 12 user buttons (D-pad, the face buttons, L, R, START, SELECT) dismisses it, but only after
// kMinMs and only after every button was released once in that time - a button still held from the XMB never skips
// it. There is no time-out. HOME -> Exit works: the exit callback (psp_system.cpp) clears systemRunning(), the
// splash returns false and main() ends the run. The press that dismissed it is handed to the port's input state as
// already held, so the login screen does not take it as a new press.
// Automation: the autopilot (autotest.txt), autologin=1 and an autopad script skip it ("splash skipped
// (automation)") - those runs have nobody to press a button, and autopad's buttons only reach the game through
// inputUpdate(), not the raw pad this screen reads.
