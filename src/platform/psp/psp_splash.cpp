bool splashRun() {
    const bool autotest = autotestActive();
    const bool autologin = configGetInt("autologin", 0) != 0;
    const bool autopad = !configGet("autopad", "").empty();
    if (autotest || autologin || autopad) {
        PSP_LOGI(tag::Boot, "splash skipped (automation) autotest=%d autologin=%d autopad=%d", autotest ? 1 : 0,
                 autologin ? 1 : 0, autopad ? 1 : 0);
        return true;
    }

    void* oldTop = nullptr;
    int oldWidth = 0, oldFormat = 0;
    sceDisplayGetFrameBuf(&oldTop, &oldWidth, &oldFormat, PSP_DISPLAY_SETBUF_NEXTFRAME);
    const uintptr_t edram = reinterpret_cast<uintptr_t>(sceGeEdramGetAddr());
    void* fb = reinterpret_cast<void*>((edram + kVramOff) | 0x40000000u);  // the uncached mirror
    volatile uint32_t* vr = static_cast<volatile uint32_t*>(fb);
    const int n = spl_qr[0];
    PSP_LOGI(tag::Boot, "splash: community QR %dx%d = %s, any button after %u ms", n, n, SPL_QR_URL, kMinMs);

    const uint64_t t0 = sceKernelGetSystemTimeWide();
    for (int y = 0; y < SPL_H; y++) drawRow(vr + y * kStride, y, SPL_LVL_DIM);
    const unsigned drawUs = static_cast<unsigned>(sceKernelGetSystemTimeWide() - t0);
    sceDisplaySetFrameBuf(fb, kStride, PSP_DISPLAY_PIXEL_FORMAT_8888, PSP_DISPLAY_SETBUF_NEXTFRAME);
    PSP_LOGI(tag::Boot, "splash: shown (VRAM %05X, 480x272 8888, drawn in %u us) - waiting for a button",
             static_cast<unsigned>(kVramOff), drawUs);

    const SplItem& pr = spl_items[SPL_PROMPT];
    bool armed = false, home = false;
    int frames = 0, lvlShown = SPL_LVL_DIM;
    uint32_t pressed = 0, heldAtStart = 0;
    unsigned ms = 0;
    for (;;) {
        sceDisplayWaitVblankStart();
        frames++;
        ms = static_cast<unsigned>((sceKernelGetSystemTimeWide() - t0) / 1000u);
        if (!systemRunning()) {
            home = true;
            break;
        }
        const int lvl = promptLevel(ms);
        if (lvl != lvlShown) {  // only the prompt's rows change
            for (int y = pr.y; y < pr.y + pr.h; y++) drawRow(vr + y * kStride, y, lvl);
            lvlShown = lvl;
        }
        SceCtrlData pad;
        std::memset(&pad, 0, sizeof(pad));
        sceCtrlPeekBufferPositive(&pad, 1);
        const uint32_t b = pad.Buttons & kKeys;
        if (frames == 1) heldAtStart = b;
        if (ms < kMinMs) continue;
        if (!armed) {  // every button released once first
            armed = b == 0;
            continue;
        }
        if (b) {
            pressed = b;
            break;
        }
    }
    sceDisplaySetFrameBuf(oldTop, oldWidth, oldFormat, PSP_DISPLAY_SETBUF_NEXTFRAME);
    sceDisplayWaitVblankStart();
    if (home) {
        PSP_LOGI(tag::Boot, "splash: HOME -> Exit while it was shown (%u ms, %d frames)", ms, frames);
        return false;
    }
    inputUpdate();  // the dismissing press becomes "held": the login screen sees no new press from it
    // held=1: a button was already down when it appeared - it waited for the release and a new press
    PSP_LOGI(tag::Boot, "splash: dismissed by a button press (buttons %04X) after %u ms, %d frames, held=%d",
             static_cast<unsigned>(pressed), ms, frames, heldAtStart ? 1 : 0);
    return true;
}

